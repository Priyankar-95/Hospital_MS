-- Appointments and Razorpay payments

CREATE TABLE appointments (
    id                        BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    booking_uuid              CHAR(36) NOT NULL,
    booking_code              VARCHAR(16) NOT NULL,
    patient_id                BIGINT UNSIGNED NOT NULL,
    doctor_id                 BIGINT UNSIGNED NOT NULL,
    schedule_id               BIGINT UNSIGNED NOT NULL,
    slot_time                 DATETIME NOT NULL,
    treatment_name            VARCHAR(150) NULL,
    fee_amount                DECIMAL(10,2) NOT NULL,
    payment_type              ENUM('ONLINE','VISIT') NOT NULL,
    payment_status            ENUM('PENDING','PAID','REFUNDED','REFUND_PENDING') NOT NULL DEFAULT 'PENDING',
    status                    ENUM('BOOKED','CANCELLED','COMPLETED','NO_SHOW') NOT NULL DEFAULT 'BOOKED',
    cancelled_by_user_id      BIGINT UNSIGNED NULL,
    cancelled_by_role         VARCHAR(30) NULL,
    cancelled_at              DATETIME NULL,
    cancel_reason             VARCHAR(500) NULL,
    payment_marked_by_user_id BIGINT UNSIGNED NULL,
    payment_marked_at         DATETIME NULL,
    created_at                DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_appt_uuid (booking_uuid),
    UNIQUE KEY uq_appt_code (booking_code),
    KEY idx_appt_patient (patient_id, slot_time),
    KEY idx_appt_doctor_slot (doctor_id, slot_time),
    KEY idx_appt_schedule (schedule_id, status),
    CONSTRAINT fk_appt_patient   FOREIGN KEY (patient_id)  REFERENCES users (id)            ON DELETE RESTRICT,
    CONSTRAINT fk_appt_doctor    FOREIGN KEY (doctor_id)   REFERENCES doctors (id)          ON DELETE RESTRICT,
    CONSTRAINT fk_appt_schedule  FOREIGN KEY (schedule_id) REFERENCES doctor_schedules (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appt_cancelled FOREIGN KEY (cancelled_by_user_id)      REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_appt_marked    FOREIGN KEY (payment_marked_by_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_appt_fee CHECK (fee_amount >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE payments (
    id                    BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    appointment_id        BIGINT UNSIGNED NOT NULL,
    razorpay_order_id     VARCHAR(64) NOT NULL,
    razorpay_payment_id   VARCHAR(64) NULL,
    amount                DECIMAL(10,2) NOT NULL,
    currency              CHAR(3) NOT NULL DEFAULT 'INR',
    status                ENUM('CREATED','PAID','FAILED','REFUND_PENDING','REFUNDED') NOT NULL DEFAULT 'CREATED',
    refund_id             VARCHAR(64) NULL,
    refund_status         VARCHAR(30) NULL,
    refunded_at           DATETIME NULL,
    created_at            DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_pay_order (razorpay_order_id),
    UNIQUE KEY uq_pay_payment (razorpay_payment_id),
    KEY idx_pay_appointment (appointment_id),
    CONSTRAINT fk_pay_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE RESTRICT,
    CONSTRAINT chk_pay_amount CHECK (amount >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
